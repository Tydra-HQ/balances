  function waterfall(steps) {
    // steps: [{label, value, total:bool}]
    var W = 540, H = 250, top = 26, bottom = 40, n = steps.length;
    var levels = [], run = 0;
    steps.forEach(function (s) {
      if (s.total) { levels.push([0, s.value]); run = s.value; }
      else { levels.push([run, run + s.value]); run += s.value; }
    });
    var vals = [];
    levels.forEach(function (l) { vals.push(l[0], l[1]); });
    var hi = Math.max.apply(null, vals), lo = Math.min.apply(null, vals);
    var tops = steps.filter(function (s) { return s.total; }).map(function (s) { return s.value; });
    var minTotal = Math.min.apply(null, tops);
    var cut = lo >= 0 && minTotal > 0 && (hi - Math.min.apply(null, levels.filter(function (l, i) { return !steps[i].total; }).map(function (l) { return Math.min(l[0], l[1]); }).concat([hi]))) < hi * 0.4;
    var base = cut ? Math.max(0, minTotal - (hi - minTotal) * 1.5 - hi * 0.05) : Math.min(0, lo);
    var span = (hi - base) || 1, ph = H - top - bottom;
    var y = function (v) { return top + (hi - v) / span * ph; };
    var gw = W / n, bw = gw * 0.6;
    var out = '<svg class="chart" viewBox="0 0 ' + W + ' ' + H + '" role="img" aria-label="waterfall">';
    out += '<line x1="0" x2="' + W + '" y1="' + (H - bottom) + '" y2="' + (H - bottom) + '" stroke="#EDE8F7" stroke-width="2"/>';
    steps.forEach(function (s, i) {
      var a = s.total ? Math.max(base, 0) : levels[i][0], b = levels[i][1];
      if (s.total && base > 0) a = base;
      var y0 = y(Math.max(a, b)), y1 = y(Math.min(a, b));
      var color = s.total ? (i === 0 ? '#9CDCD2' : '#12A594') : (s.value >= 0 ? '#2F9E5B' : '#F2545B');
      var ink = s.total ? '#1F1636' : (s.value >= 0 ? '#1B6B3B' : '#9E1F26');
      var x0 = i * gw + (gw - bw) / 2;
      out += '<rect class="bar" x="' + x0.toFixed(1) + '" y="' + y0.toFixed(1) + '" width="' + bw.toFixed(1) + '" height="' + Math.max(y1 - y0, 2).toFixed(1) + '" rx="6" fill="' + color + '"/>';
      out += '<text x="' + (i * gw + gw / 2).toFixed(1) + '" y="' + (y0 - 6).toFixed(1) + '" text-anchor="middle" font-size="12" font-weight="700" fill="' + ink + '">' + esc((s.total || s.value < 0 ? '' : '+') + num(s.value)) + '</text>';
      out += '<text x="' + (i * gw + gw / 2).toFixed(1) + '" y="' + (H - bottom + 18) + '" text-anchor="middle" font-size="11.5" font-weight="600" fill="#5E5675">' + esc(s.label) + '</text>';
    });
    return { svg: out + '</svg>', cut: cut };
  }


  // ------------------------------------------------------------ loading screen
  function showReport(ticker) {
    loadCompanies().then(function (list) {
      var c = list.filter(function (x) { return x.ticker === ticker; })[0];
      var name = c ? (c.legal || c.name) : ticker;
      var step = 0, fetched = null, failed = false;
      var drawLoading = function () {
        var L = t();
        app.innerHTML = '<div class="loading rise"><p class="note"><b>' + esc(L.loadingTitle) + '</b></p><h2>' + esc(name) + '</h2>' +
          '<div class="prog">' + L.steps.map(function (s, i) { return '<i class="' + (i < step ? 'done' : i === step ? 'now' : '') + '"></i>'; }).join('') + '</div>' +
          '<ol class="steps">' + L.steps.map(function (s, i) {
            var icon = i < step
              ? '<svg width="26" height="26" viewBox="0 0 24 24" aria-hidden="true"><circle cx="12" cy="12" r="11" fill="#12A594"/><path d="M7 12.5l3.2 3.2L17 9" fill="none" stroke="#fff" stroke-width="2.4" stroke-linecap="round" stroke-linejoin="round"/></svg>'
              : i === step
                ? '<svg class="spinner" width="26" height="26" viewBox="0 0 24 24" aria-hidden="true"><circle cx="12" cy="12" r="10" fill="none" stroke="#EDE8F7" stroke-width="3"/><path d="M12 2a10 10 0 0 1 10 10" fill="none" stroke="#F5A524" stroke-width="3" stroke-linecap="round"/></svg>'
                : '<svg width="26" height="26" viewBox="0 0 24 24" aria-hidden="true"><circle cx="12" cy="12" r="10" fill="none" stroke="#CFC6E0" stroke-width="2"/></svg>';
            return '<li class="' + (i < step ? 'done' : i === step ? 'now' : '') + '">' + icon + '<span>' + esc(s) + '</span></li>';
          }).join('') + '</ol></div>';
      };
      var cached = S.cache[ticker];
      if (cached) { renderReport(cached); return; }
      drawLoading();
      getJSON('data/' + ticker + '.json').then(function (d) { fetched = d; S.cache[ticker] = d; })
        .catch(function () { failed = true; });
      var tick = function () {
        S.timer = setTimeout(function () {
          if (location.hash.toUpperCase() !== ('#/' + ticker)) return;
          if (step < 3) { step++; drawLoading(); tick(); return; }
          if (fetched) renderReport(fetched);
          else if (failed) renderError();
          else tick();
        }, 520);
      };
      tick();
    });
  }

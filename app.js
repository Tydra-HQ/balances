  function num(v, dec) {
    if (v == null || isNaN(v)) return t().na;
    var es = S.lang === 'es';
    var s = Math.abs(v).toFixed(dec || 0);
    var p = s.split('.');
    var i = p[0];
    if (!(es && (dec || 0) === 0 && i.length === 4)) i = i.replace(/\B(?=(\d{3})+(?!\d))/g, es ? '.' : ',');
    return (v < 0 ? '−' : '') + (p.length > 1 ? i + (es ? ',' : '.') + p[1] : i);
  }
  function pct(v, signed) {
    if (v == null || isNaN(v)) return t().na;
    var s = num(Math.abs(v), 1) + '%';
    return signed ? (v >= 0 ? '+' : '−') + s : (v < 0 ? '−' : '') + s;
  }
  function chg(a, b) { return a == null || b == null || b <= 0 ? null : (a / b - 1) * 100; }
